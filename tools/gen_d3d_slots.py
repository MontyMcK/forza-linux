#!/usr/bin/env python3
"""Generate src/hle/d3d11x/desktop_slots.h: the *desktop* (public SDK) vtable
slot order of the D3D11/DXGI interfaces, read from the C-style Vtbl structs in
DXVK's MinGW headers. DXVK objects use this order; the game's Xbox objects do
not (see docs/FINDINGS.md §3), so every call into DXVK goes through these enums.

Usage: python3 tools/gen_d3d_slots.py > src/hle/d3d11x/desktop_slots.h
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HDRS = os.path.join(ROOT, "third_party/dxvk/include/native/directx")

# (header, interface, enum namespace)
WANT = [
    ("d3d11_2.h", "ID3D11Device2", "dev"),
    ("d3d11_2.h", "ID3D11DeviceContext2", "ctx"),
    ("dxgi1_2.h", "IDXGIDevice2", "dxgidev"),
    ("dxgi1_2.h", "IDXGIAdapter2", "adapter"),
    ("dxgi1_2.h", "IDXGIOutput1", "output"),
    ("dxgi1_2.h", "IDXGIFactory2", "factory"),
    ("dxgi1_2.h", "IDXGISwapChain1", "swapchain"),
]


def methods(header, iface):
    text = open(os.path.join(HDRS, header)).read()
    m = re.search(r"typedef struct %sVtbl \{(.*?)\} %sVtbl;" % (iface, iface), text, re.S)
    if not m:
        sys.exit("no %sVtbl in %s" % (iface, header))
    return re.findall(r"\(STDMETHODCALLTYPE \*(\w+)\)", m.group(1))


print("// GENERATED by tools/gen_d3d_slots.py from DXVK's MinGW headers. Do not edit.")
print("// Desktop (public SDK) slot numbers. Use these ONLY for calls into DXVK.")
print("#pragma once\n")
print("#include \"common/winabi.h\"\n")
print("namespace fl::d3d::desktop {")
for header, iface, ns in WANT:
    names = methods(header, iface)
    print("\n// %s (%s), %d slots" % (iface, header, len(names)))
    print("namespace %s {\nenum : int {" % ns)
    for i, n in enumerate(names):
        print("    %s = %d," % (n, i))
    print("    kCount = %d,\n};\n}  // namespace %s" % (len(names), ns))
print("\n}  // namespace fl::d3d::desktop")

# Public IIDs, read from DEFINE_GUID lines.
IIDS = [
    "ID3D11DeviceChild", "ID3D11Resource", "ID3D11Buffer", "ID3D11Texture1D", "ID3D11Texture2D",
    "ID3D11Texture3D", "ID3D11View", "ID3D11ShaderResourceView", "ID3D11RenderTargetView",
    "ID3D11DepthStencilView", "ID3D11UnorderedAccessView", "ID3D11VertexShader", "ID3D11HullShader",
    "ID3D11DomainShader", "ID3D11GeometryShader", "ID3D11PixelShader", "ID3D11ComputeShader",
    "ID3D11InputLayout", "ID3D11SamplerState", "ID3D11BlendState", "ID3D11DepthStencilState",
    "ID3D11RasterizerState", "ID3D11Asynchronous", "ID3D11Query", "ID3D11Predicate", "ID3D11Counter",
    "ID3D11CommandList", "ID3D11ClassLinkage", "ID3D11BlendState1", "ID3D11RasterizerState1",
    "ID3D11DeviceContext", "ID3D11DeviceContext1", "ID3D11DeviceContext2",
    "ID3D11Device", "ID3D11Device1", "ID3D11Device2",
    "IDXGIObject", "IDXGIDeviceSubObject", "IDXGIResource", "IDXGISurface", "IDXGISurface1",
    "IDXGIDevice", "IDXGIDevice1", "IDXGIDevice2", "IDXGIAdapter", "IDXGIAdapter1", "IDXGIOutput",
    "IDXGIFactory", "IDXGIFactory1", "IDXGIFactory2", "IDXGISwapChain", "IDXGISwapChain1",
]
alltext = "".join(open(os.path.join(HDRS, h)).read() for h in sorted(os.listdir(HDRS)) if h.endswith(".h"))
print("\n// Public IIDs (from the same headers).")
print("namespace fl::d3d {")
for name in IIDS:
    m = re.search(r"DEFINE_GUID\(IID_%s,\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*"
                  r"((?:0x[0-9a-fA-F]+,\s*){7}0x[0-9a-fA-F]+)\)" % name, alltext)
    if not m:
        sys.exit("no IID for " + name)
    b = ", ".join(x.strip() for x in m.group(4).split(","))
    print("constexpr GUID IID_%s = {%s, %s, %s, {%s}};" % (name, m.group(1), m.group(2), m.group(3), b))
print("}  // namespace fl::d3d")
